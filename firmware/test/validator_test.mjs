#!/usr/bin/env node
// Generator maintenance regressions, independent of the Arduino build.
import assert from 'node:assert/strict';
import {cpSync, mkdirSync, readFileSync, writeFileSync, unlinkSync} from 'node:fs';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
import {generateValidator, validatorPath} from '../tools/generate_validator.mjs';
import {repo, run, capture, sha256, temporary, verifyValidator} from './host_support.mjs';

verifyValidator();
temporary('sentinel validator paths with spaces ', directory => {
  const schemas = join(directory,'repo with spaces/contracts/schemas/v2');
  cpSync(join(repo,'contracts/schemas/v2'),schemas,{recursive:true});
  const output = join(directory,'distributed source with spaces/v2_validator.h');
  mkdirSync(join(directory,'distributed source with spaces'));
  const script = join(repo,'firmware/tools/generate_validator.mjs');
  const command = [script,output,'--schemas',schemas];
  run(process.execPath,command);
  const original = readFileSync(output);
  assert.deepEqual(original, readFileSync(validatorPath));
  assert.equal(sha256(original),sha256(Buffer.from(generateValidator())));
  capture(process.execPath,[...command,'--check']);
  const common = join(schemas,'common.schema.json');
  const schema = JSON.parse(readFileSync(common,'utf8'));
  schema.$defs.maintenance_test = {type:'string',const:'new-schema-value'};
  writeFileSync(common,JSON.stringify(schema));
  const stale = spawnSync(process.execPath,[...command,'--check'],{encoding:'utf8'});
  assert.notEqual(stale.status,0);
  assert.match(stale.stderr,/Validator differs/);
  run(process.execPath,command);
  assert.notDeepEqual(original,readFileSync(output));
  assert.match(readFileSync(output,'utf8'),/new-schema-value/);
  const reviewed = readFileSync(output);
  schema.$defs.maintenance_test.unsupported_keyword = true;
  writeFileSync(common,JSON.stringify(schema));
  const rejected = spawnSync(process.execPath,command,{encoding:'utf8'});
  assert.notEqual(rejected.status,0);
  assert.match(rejected.stderr,/Unsupported schema keywords/);
  assert.deepEqual(readFileSync(output),reviewed,'A failed maintenance generation cannot overwrite source');
  delete schema.$defs.maintenance_test.unsupported_keyword;
  schema.$defs.maintenance_test.pattern = '^unsupported-pattern$';
  writeFileSync(common,JSON.stringify(schema));
  const pattern = spawnSync(process.execPath,command,{encoding:'utf8'});
  assert.notEqual(pattern.status,0);
  assert.match(pattern.stderr,/Unsupported schema pattern/);
  delete schema.$defs.maintenance_test.pattern;
  schema.$defs.maintenance_test.$ref = 'https://untrusted.invalid/common.schema.json#/$defs/V2Identifier';
  writeFileSync(common,JSON.stringify(schema));
  const reference = spawnSync(process.execPath,command,{encoding:'utf8'});
  assert.notEqual(reference.status,0);
  assert.match(reference.stderr,/Unsupported schema reference/);
  const absentArgument = spawnSync(process.execPath,[script,output,'--schemas'],{encoding:'utf8'});
  assert.notEqual(absentArgument.status,0);
  assert.match(absentArgument.stderr,/requires a directory/);
  unlinkSync(common);
  const missing = spawnSync(process.execPath,command,{encoding:'utf8'});
  assert.notEqual(missing.status,0);
  assert.match(missing.stderr,/ENOENT/);
  assert.deepEqual(readFileSync(output),reviewed);
});
console.log('Validator schema equivalence, drift, paths with spaces and fail-closed maintenance: PASS');
